create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  username text not null check (char_length(username) between 1 and 60),
  content text,
  image_url text,
  created_at timestamptz not null default now(),
  constraint messages_content_or_image check (
    nullif(trim(coalesce(content, '')), '') is not null or
    nullif(trim(coalesce(image_url, '')), '') is not null
  )
);

alter table public.messages enable row level security;

drop policy if exists "Authenticated users can read messages" on public.messages;
create policy "Authenticated users can read messages"
on public.messages for select to authenticated using (true);

drop policy if exists "Users can send their own messages" on public.messages;
create policy "Users can send their own messages"
on public.messages for insert to authenticated
with check (auth.uid() = user_id);

grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

-- Enable realtime for the chat table (safe to run more than once).
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;

-- Public image URLs; only signed-in users may upload into their own folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('chat-images', 'chat-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Anyone can view chat images" on storage.objects;
create policy "Anyone can view chat images"
on storage.objects for select
using (bucket_id = 'chat-images');

drop policy if exists "Users can upload chat images to own folder" on storage.objects;
create policy "Users can upload chat images to own folder"
on storage.objects for insert to authenticated
with check (
  bucket_id = 'chat-images'
  and (storage.foldername(name))[1] = auth.uid()::text
);
