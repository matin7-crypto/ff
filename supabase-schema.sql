-- این دستورات را در Supabase > SQL Editor اجرا کن.
create table if not exists public.messages (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 username text not null default 'کاربر',
 content text,
 image_url text,
 created_at timestamptz not null default now(),
 constraint message_has_content check (nullif(trim(coalesce(content,'')),'') is not null or image_url is not null)
);
alter table public.messages enable row level security;
drop policy if exists "Signed-in users can read messages" on public.messages;
create policy "Signed-in users can read messages" on public.messages for select to authenticated using (true);
drop policy if exists "Users can send messages as themselves" on public.messages;
create policy "Users can send messages as themselves" on public.messages for insert to authenticated with check (auth.uid()=user_id);
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('chat-images','chat-images',true,5242880,array['image/jpeg','image/png','image/webp','image/gif'])
on conflict(id) do update set public=true,file_size_limit=5242880;
drop policy if exists "Signed-in users can upload chat images" on storage.objects;
create policy "Signed-in users can upload chat images" on storage.objects for insert to authenticated
with check(bucket_id='chat-images' and (storage.foldername(name))[1]=auth.uid()::text);
drop policy if exists "Anyone can view chat images" on storage.objects;
create policy "Anyone can view chat images" on storage.objects for select to public using(bucket_id='chat-images');
